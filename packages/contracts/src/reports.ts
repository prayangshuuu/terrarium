export function validateReportDisagreement(
  value: unknown,
  path = "disagreement"
): Result<ReportDisagreement, ValidationIssue[]> {
  if (!isRecord(value)) {
    return fail([{ path, message: "Expected object for ReportDisagreement", received: value }]);
  }

  const collector = new ValidationCollector();

  const id = collector.check(validateString(value.id, `${path}.id`, { minLength: 1, maxLength: 100 }));
  const topic = collector.check(validateString(value.topic, `${path}.topic`, { minLength: 1, maxLength: 200 }));
  const summary = collector.check(validateString(value.summary, `${path}.summary`, { minLength: 1, maxLength: 2000 }));
  const resolutionStatus = collector.check(
    validateEnum(value.resolutionStatus, `${path}.resolutionStatus`, [
      "unresolved",
      "compromise",
      "acknowledged_tradeoff",
    ] as const)
  );

  const perspectives = collector.check(
    validateArray<DisagreementPerspective>(value.perspectives ?? [], `${path}.perspectives`, (p, pPath) => {
      if (!isRecord(p)) {
        return fail({ path: pPath, message: "Expected object for DisagreementPerspective", received: p });
      }
      if (typeof p.participantId !== "string" || !p.participantId) {
        return fail({ path: `${pPath}.participantId`, message: "Participant ID must be non-empty", received: p.participantId });
      }
      if (typeof p.participantName !== "string" || !p.participantName) {
        return fail({ path: `${pPath}.participantName`, message: "Participant Name must be non-empty", received: p.participantName });
      }
      if (typeof p.stance !== "string" || !p.stance) {
        return fail({ path: `${pPath}.stance`, message: "Stance must be non-empty", received: p.stance });
      }
      if (typeof p.rationale !== "string" || !p.rationale) {
        return fail({ path: `${pPath}.rationale`, message: "Rationale must be non-empty", received: p.rationale });
      }
      return ok({
        participantId: p.participantId,
        participantName: p.participantName,
        isSimulatedPersona: Boolean(p.isSimulatedPersona),
        stance: p.stance,
        rationale: p.rationale,
      });
    })
  );

  if (
    collector.hasIssues() ||
    id === undefined ||
    topic === undefined ||
    summary === undefined ||
    resolutionStatus === undefined
  ) {
    return fail(collector.issues);
  }

  return ok({
    id,
    topic,
    summary,
    perspectives: perspectives ?? [],
    resolutionStatus,
    tradeOffImplication: typeof value.tradeOffImplication === "string" ? value.tradeOffImplication : undefined,
  });
}

