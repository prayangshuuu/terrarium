export function validateReport(
  value: unknown,
  path = "report"
): Result<Report, DomainValidationError> {
  if (!isRecord(value)) {
    return fail(
      new DomainValidationError(`Expected object for ${path}`, [
        { path, message: "Expected object", received: value },
      ])
    );
  }

  const collector = new ValidationCollector();

  const id = collector.check(validateString(value.id, `${path}.id`, { minLength: 1, maxLength: 100 }));
  const taskId = collector.check(validateString(value.taskId, `${path}.taskId`, { minLength: 1, maxLength: 100 }));
  const title = collector.check(validateString(value.title, `${path}.title`, { minLength: 1, maxLength: 200 }));
  const reportType = collector.check(validateEnum(value.reportType, `${path}.reportType`, REPORT_TYPES));
  const summary = collector.check(
    validateString(value.summary, `${path}.summary`, { minLength: 1, maxLength: 5000 })
  );
  const markdownContent = collector.check(
    validateString(value.markdownContent, `${path}.markdownContent`, { minLength: 1, maxLength: 500000 })
  );
  const status = collector.check(validateEnum(value.status, `${path}.status`, ["draft", "final"] as const));
  const createdAt = collector.check(validateIsoDateTime(value.createdAt, `${path}.createdAt`));
  const updatedAt = collector.check(validateIsoDateTime(value.updatedAt, `${path}.updatedAt`));

  // Structured fields with graceful fallback for backwards compatibility
  const rawObjective = typeof value.objective === "string" && value.objective.trim() ? value.objective : value.summary;
  const objective = collector.check(
    validateString(rawObjective, `${path}.objective`, { minLength: 1, maxLength: 5000 })
  );

  const rawMethod = typeof value.method === "string" && value.method.trim() ? value.method : "Multi-agent synthesis and artifact analysis";
  const method = collector.check(
    validateString(rawMethod, `${path}.method`, { minLength: 1, maxLength: 5000 })
  );

  const confidence = collector.check(
    validateEnum(value.confidence ?? "high", `${path}.confidence`, CONFIDENCE_LEVELS)
  );

  const findings = collector.check(
    validateArray<ReportFinding>(value.findings ?? [], `${path}.findings`, (f, fPath) => {
      const fRes = validateReportFinding(f, fPath);
      if (!fRes.success) return fail(fRes.error[0] ?? { path: fPath, message: "Invalid finding" });
      return ok(fRes.data);
    })
  );

  const evidence = collector.check(
    validateArray<ReportEvidenceItem>(value.evidence ?? [], `${path}.evidence`, (e, ePath) => {
      const eRes = validateReportEvidenceItem(e, ePath);
      if (!eRes.success) return fail(eRes.error[0] ?? { path: ePath, message: "Invalid evidence item" });
      return ok(eRes.data);
    })
  );

  const sources = collector.check(
    validateArray<ReportSource>(value.sources ?? [], `${path}.sources`, (s, sPath) => {
      const sRes = validateReportSource(s, sPath);
      if (!sRes.success) return fail(sRes.error[0] ?? { path: sPath, message: "Invalid report source" });
      return ok(sRes.data);
    })
  );

  const assumptions = collector.check(
    validateArray(value.assumptions ?? [], `${path}.assumptions`, (a, aPath) =>
      validateString(a, aPath, { minLength: 1, maxLength: 2000 })
    )
  );

  const limitations = collector.check(
    validateArray(value.limitations ?? [], `${path}.limitations`, (l, lPath) =>
      validateString(l, lPath, { minLength: 1, maxLength: 2000 })
    )
  );

  const disagreements = collector.check(
    validateArray<ReportDisagreement>(value.disagreements ?? [], `${path}.disagreements`, (d, dPath) => {
      const dRes = validateReportDisagreement(d, dPath);
      if (!dRes.success) return fail(dRes.error[0] ?? { path: dPath, message: "Invalid disagreement" });
      return ok(dRes.data);
    })
  );

  const recommendations = collector.check(
    validateArray<ReportRecommendation>(value.recommendations ?? [], `${path}.recommendations`, (r, rPath) => {
      const rRes = validateReportRecommendation(r, rPath);
      if (!rRes.success) return fail(rRes.error[0] ?? { path: rPath, message: "Invalid recommendation" });
      return ok(rRes.data);
    })
  );

  const agentsInvolved = collector.check(
    validateArray(value.agentsInvolved ?? [], `${path}.agentsInvolved`, (a, aPath) =>
      validateString(a, aPath, { minLength: 1, maxLength: 100 })
    )
  );

  const hasSimulatedData = Boolean(
    value.hasSimulatedData ||
    value.reportType === "customer_simulation" ||
    (evidence && evidence.some((e) => e.claimType === "simulated_feedback")) ||
    (findings && findings.some((f) => f.isSimulated))
  );

  if (
    collector.hasIssues() ||
    id === undefined ||
    taskId === undefined ||
    title === undefined ||
    reportType === undefined ||
    summary === undefined ||
    objective === undefined ||
    method === undefined ||
    confidence === undefined ||
    markdownContent === undefined ||
    status === undefined ||
    createdAt === undefined ||
    updatedAt === undefined
  ) {
    return fail(collector.toError("Report validation failed"));
  }

  return ok({
    id,
    taskId,
    title,
    reportType,
    summary,
    objective,
    method,
    evidence: evidence ?? [],
    sources: sources ?? [],
    assumptions: assumptions ?? [],
    confidence,
    confidenceRationale: typeof value.confidenceRationale === "string" ? value.confidenceRationale : undefined,
    limitations: limitations ?? [],
    disagreements: disagreements ?? [],
    recommendations: recommendations ?? [],
    hasSimulatedData,
    simulationMetadata: isRecord(value.simulationMetadata) ? (value.simulationMetadata as any) : undefined,
    findings: findings ?? [],
    markdownContent,
    agentsInvolved: agentsInvolved ?? [],
    status,
    createdAt,
    updatedAt,
  });
}
